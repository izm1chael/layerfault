static RULESET_SHA256: OnceLock<String> = OnceLock::new();

/// Deterministic SHA256 ruleset digest computed over machine metadata.
///
/// Prose fields (title, meaning, why_it_matters, remediation, limitations)
/// are explicitly excluded so wording updates do not invalidate semantic comparison.
pub fn ruleset_sha256() -> &'static str {
    RULESET_SHA256.get_or_init(|| {
        let mut rules: Vec<_> = CATALOGUE.iter().collect();
        rules.sort_by_key(|r| r.rule_id);
        let mut hasher = Sha256::new();
        hasher.update(b"layerfault-ruleset-identity ");
        for rule in rules {
            hasher.update(rule.rule_id.as_bytes());
            hasher.update([0]);
            hasher.update(rule.rule_version.to_le_bytes());
            hasher.update([0]);
            hasher.update(rule.detector_family.as_bytes());
            hasher.update([0]);
            let req_byte = match rule.evidence_requirement {
                EvidenceRequirement::Required => 1u8,
                EvidenceRequirement::StructuredOnly => 2u8,
                EvidenceRequirement::NotApplicable => 3u8,
            };
            hasher.update([req_byte]);
            hasher.update([0xff]);
        }
        let digest = hasher.finalize();
        let mut hex = String::with_capacity(64);
        for byte in digest {
            let _ = write!(&mut hex, "{byte:02x}");
        }
        format!("sha256:{hex}")
    })
}

